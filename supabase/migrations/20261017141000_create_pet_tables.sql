create table public.pet_devices (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null references auth.users(id) on delete cascade,
    device_key text not null check (char_length(device_key) between 1 and 128),
    display_name text check (display_name is null or char_length(display_name) <= 80),
    last_seen_at timestamptz not null default now(),
    created_at timestamptz not null default now(),
    unique (user_id, device_key)
);

create table public.pet_events (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    device_id uuid references public.pet_devices(id) on delete set null,
    event_type text not null check (event_type in ('tap', 'rapid_tap', 'drag', 'charging', 'idle', 'app_open')),
    payload jsonb not null default '{}'::jsonb check (jsonb_typeof(payload) = 'object'),
    created_at timestamptz not null default now()
);

create table public.pet_commands (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null references auth.users(id) on delete cascade,
    device_id uuid references public.pet_devices(id) on delete cascade,
    command_type text not null default 'bubble' check (command_type = 'bubble'),
    state text not null default 'idle' check (state in ('idle', 'blink', 'tap', 'rapid-tap', 'drag', 'sleep', 'perch')),
    text text not null check (char_length(trim(text)) between 1 and 36),
    duration_ms integer not null default 4000 check (duration_ms between 500 and 15000),
    created_at timestamptz not null default now(),
    expires_at timestamptz,
    consumed_at timestamptz,
    check (expires_at is null or expires_at > created_at)
);

create index pet_devices_user_id_idx on public.pet_devices(user_id);
create index pet_events_user_created_idx on public.pet_events(user_id, created_at desc);
create index pet_commands_pending_idx on public.pet_commands(user_id, created_at)
    where consumed_at is null;

alter table public.pet_devices enable row level security;
alter table public.pet_events enable row level security;
alter table public.pet_commands enable row level security;

revoke all on public.pet_devices, public.pet_events, public.pet_commands from anon;
grant select, insert, update, delete on public.pet_devices to authenticated;
grant select, insert on public.pet_events to authenticated;
grant select, update on public.pet_commands to authenticated;
grant usage, select on sequence public.pet_events_id_seq to authenticated;

create policy "pet_devices_select_own"
on public.pet_devices for select to authenticated
using ((select auth.uid()) = user_id);

create policy "pet_devices_insert_own"
on public.pet_devices for insert to authenticated
with check ((select auth.uid()) = user_id);

create policy "pet_devices_update_own"
on public.pet_devices for update to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

create policy "pet_devices_delete_own"
on public.pet_devices for delete to authenticated
using ((select auth.uid()) = user_id);

create policy "pet_events_select_own"
on public.pet_events for select to authenticated
using ((select auth.uid()) = user_id);

create policy "pet_events_insert_own"
on public.pet_events for insert to authenticated
with check (
    (select auth.uid()) = user_id
    and (
        device_id is null
        or exists (
            select 1 from public.pet_devices d
            where d.id = device_id and d.user_id = (select auth.uid())
        )
    )
);

create policy "pet_commands_select_own"
on public.pet_commands for select to authenticated
using ((select auth.uid()) = user_id);

create policy "pet_commands_acknowledge_own"
on public.pet_commands for update to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

